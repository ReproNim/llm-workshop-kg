"""Validate graphs against SHACL generated from PyNIDM's LinkML NIDM schema (v4.5.5).

Shapes: data/vocab/nidm/nidm_linkml_shapes_open.ttl (gen-shacl --non-closed) and
nidm_linkml_shapes_closed.ttl (--closed), generated by `linkml gen-shacl`.
Targets: our core graph (dataset layer), the PyNIDM csv2nidm phenotype graph, and one ReproNim
simple2 site graph, so the same rules are applied to all three.
Also declares every urn:repronim:abide: class and property we use that the schema has no slot for
(graph/abide_extension.ttl).

Usage: uv run python code/validate_linkml.py
"""

import collections
import json
import time

from pyshacl import validate
from rdflib import OWL, RDF, RDFS, Graph, Literal, Namespace, URIRef

from common import DATA, GRAPH, write_json

SH = Namespace("http://www.w3.org/ns/shacl#")
E = "urn:repronim:abide:"
TARGETS = {
    "abide_core": GRAPH / "abide_kg.ttl",
    "pynidm_csv2nidm_phenotype": DATA / "derived/pynidm/phenotype_pynidm.ttl",
    "repronim_simple2_Caltech": DATA / "repronim_simple2/datasets.datalad.org/abide/RawDataBIDS/Caltech/nidm.ttl",
}


def summarize(report: Graph, shapes: Graph) -> dict:
    """Count violations by source shape and path."""
    by = collections.Counter()
    for r in report.subjects(RDF.type, SH.ValidationResult):
        shape = report.value(r, SH.sourceShape)
        node_shape = next((s for s in shapes.subjects(SH.property, shape)), shape)
        path = report.value(r, SH.resultPath)
        comp = report.value(r, SH.sourceConstraintComponent)
        by[f"{str(node_shape).rsplit('/', 1)[-1].rsplit('#', 1)[-1]} | {str(path).rsplit('/', 1)[-1].rsplit('#', 1)[-1]} | {str(comp).rsplit('#', 1)[-1]}"] += 1
    return dict(by.most_common())


def extension(g: Graph) -> Graph:
    """Declare our own classes and predicates as an explicit extension of NIDM."""
    ext = Graph()
    ext.bind("ex", Namespace(E))
    onto = URIRef(E + "extension")
    ext.add((onto, RDF.type, OWL.Ontology))
    ext.add((onto, RDFS.comment, Literal("Terms used by this experiment that NIDM LinkML schema 0.1.0 (PyNIDM v4.5.5) has no class or slot for.")))
    classes = {o for o in g.objects(None, RDF.type) if str(o).startswith(E)}
    preds = {p for p in g.predicates() if str(p).startswith(E) and "/variable/" not in str(p)}
    for c in sorted(classes):
        ext.add((c, RDF.type, OWL.Class))
        ext.add((c, RDFS.isDefinedBy, onto))
    for p in sorted(preds):
        ext.add((p, RDF.type, RDF.Property))
        ext.add((p, RDFS.isDefinedBy, onto))
    ext.serialize(GRAPH / "abide_extension.ttl", format="turtle")
    return ext


def main() -> None:
    """Validate every target with open and closed shapes."""
    out = {"schema": "PyNIDM v4.5.5 src/nidm/experiment/schema/nidm_schema.yaml (LinkML 0.1.0)",
           "pynidm_commit": (DATA / "vocab/nidm/pynidm_v4.5.5.commit").read_text().strip(), "targets": {}}
    for name, path in TARGETS.items():
        g = Graph().parse(path)
        rec = {"file": str(path.relative_to(DATA.parent)), "triples": len(g)}
        for mode in ("open", "closed"):
            t0 = time.time()
            shapes = Graph().parse(DATA / f"vocab/nidm/nidm_linkml_shapes_{mode}.ttl")
            ok, report, _ = validate(g, shacl_graph=shapes, inference="none", allow_warnings=True)
            viol = summarize(report, shapes)
            rec[mode] = {"conforms": ok, "n_results": sum(viol.values()), "by_shape_path_constraint": dict(list(viol.items())[:25]), "seconds": round(time.time() - t0, 1)}
        out["targets"][name] = rec
        print(name, {m: (rec[m]["conforms"], rec[m]["n_results"]) for m in ("open", "closed")}, flush=True)
    ext = extension(Graph().parse(GRAPH / "abide_kg.ttl"))
    out["extension"] = {"file": "graph/abide_extension.ttl",
                        "n_classes": len(set(ext.subjects(RDF.type, OWL.Class))),
                        "n_properties": len(set(ext.subjects(RDF.type, RDF.Property))),
                        "classes": sorted(str(c).replace(E, "ex:") for c in ext.subjects(RDF.type, OWL.Class))}
    write_json("linkml_validation.json", out)
    print(json.dumps({k: v for k, v in out["extension"].items() if k != "classes"}))


if __name__ == "__main__":
    main()
